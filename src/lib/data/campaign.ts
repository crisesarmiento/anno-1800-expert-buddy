export const missionsById: Record<string, Mission> = Object.fromEntries(
  missions.map((mission) => [mission.id, mission]),
);

export const chaptersById: Record<string, Chapter> = Object.fromEntries(
  chapters.map((chapter) => [chapter.id, chapter]),
);

export function getChapterForMission(missionId: string): Chapter | undefined {
  const mission = missionsById[missionId];
  if (!mission) return undefined;
  return chaptersById[mission.chapterId];
}

export function getMissionIndex(missionId: string): {
  chapter: Chapter;
  index: number;
  total: number;
  nextId?: string;
  prevId?: string;
} | null {
  const mission = missionsById[missionId];
  const chapter = mission ? chaptersById[mission.chapterId] : undefined;
  if (!mission || !chapter) return null;
  const index = chapter.missionIds.indexOf(missionId);
  return {
    chapter,
    index,
    total: chapter.missionIds.length,
    nextId: chapter.missionIds[index + 1],
    prevId: chapter.missionIds[index - 1],
  };
}
